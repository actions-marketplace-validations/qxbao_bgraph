package godyn

import (
	"strings"
	"testing"
)

const cartGo = `// Package shop is a test fixture.
package shop

import "strings"

// Limit is the largest cart.
const Limit = 10

var greeting = "hi"

// Cart holds items.
type Cart struct{ items []int }

// Total sums the items.
func (c *Cart) Total() int {
	n := 0
	for _, x := range c.items {
		n += x
	}
	return n
}

func (c Cart) Count() int { return len(c.items) }

//go:noinline
func Describe(c *Cart) string {
	return strings.Repeat("x", c.Count())
}

func Map[T any](xs []T, f func(T) T) []T {
	for i := range xs {
		xs[i] = f(xs[i])
	}
	return xs
}

func Empty() {}
`

func TestBodyGuardAccepts(t *testing.T) {
	cases := []struct {
		name      string
		old, new  string
		wantSpans []string
		shift     bool
		first     int
	}{
		{"body change", "n += x", "n += x * 1", []string{"Cart.Total:15-21"}, false, 0},
		{"one-line method", "return len(c.items) }", "return len(c.items) + 0 }", []string{"Cart.Count:23-23"}, false, 0},
		{"generic body", "xs[i] = f(xs[i])", "xs[i] = f(f(xs[i]))", []string{"Map:30-35"}, false, 0},
		{"empty body filled", "func Empty() {}", "func Empty() { _ = 1 }", []string{"Empty:37-37"}, false, 0},
		{"closure and local const", "return strings.Repeat(\"x\", c.Count())", "const k = 1\n\tf := func() int { return k }\n\treturn strings.Repeat(\"x\", c.Count()+f()-1)", []string{"Describe:26-28"}, true, 27},
		{"comment only", "// Total sums the items.", "// Total sums the items, all of them.", nil, false, 0},
		{"comment added: shift", "// Cart holds items.", "// Cart holds items.\n// More.", nil, true, 12},
		{"comment in a body", "n := 0", "n := 0 // start", nil, false, 0},
	}
	for _, c := range cases {
		head := strings.Replace(cartGo, c.old, c.new, 1)
		if head == cartGo {
			t.Fatalf("%s: no change", c.name)
		}
		spans, shift, first, why := BodyGuard("shop.go", []byte(cartGo), []byte(head))
		if why != "" {
			t.Errorf("%s: refused: %s", c.name, why)
			continue
		}
		var got []string
		for _, s := range spans {
			got = append(got, s.What+":"+itoa(s.From)+"-"+itoa(s.To))
		}
		if strings.Join(got, ",") != strings.Join(c.wantSpans, ",") || shift != c.shift || first != c.first {
			t.Errorf("%s: spans %v shift %v first %d, want %v %v %d", c.name, got, shift, first, c.wantSpans, c.shift, c.first)
		}
	}
}

func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	s := ""
	for n > 0 {
		s = string(rune('0'+n%10)) + s
		n /= 10
	}
	return s
}

// Every change outside function bodies, and every file kind the guard cannot judge, refuses.
func TestBodyGuardRefuses(t *testing.T) {
	cases := []struct {
		name     string
		old, new string
		base     string // replaces cartGo at both sides when set (old/new then apply to it)
		want     string
	}{
		{name: "signature", old: "func Describe(c *Cart) string", new: "func Describe(c *Cart, _ int) string", want: "outside function bodies"},
		{name: "receiver", old: "func (c Cart) Count() int", new: "func (c *Cart) Count() int", want: "outside function bodies"},
		{name: "type parameter", old: "func Map[T any]", new: "func Map[T comparable]", want: "outside function bodies"},
		{name: "const", old: "const Limit = 10", new: "const Limit = 11", want: "outside function bodies"},
		{name: "var initializer", old: `var greeting = "hi"`, new: `var greeting = "hello"`, want: "outside function bodies"},
		{name: "type", old: "type Cart struct{ items []int }", new: "type Cart struct{ items []int64 }", want: "outside function bodies"},
		{name: "import", old: `import "strings"`, new: "import (\n\t\"strings\"\n\t_ \"fmt\"\n)", want: "outside function bodies"},
		{name: "go:noinline removed", old: "//go:noinline\n", new: "", want: "outside function bodies"},
		{name: "go:embed", old: "var greeting = \"hi\"", new: "//go:embed x.txt\nvar greeting = \"hi\"", want: "outside function bodies"},
		{name: "go:linkname", old: "func Empty() {}", new: "func Empty() {}\n\n//go:linkname empty Empty", want: "outside function bodies"},
		{name: "new function", old: "func Empty() {}", new: "func Empty() {}\n\nfunc Other() {}", want: "outside function bodies"},
		{name: "build constraint", old: "// Package shop", new: "//go:build linux\n\n// Package shop", want: "build constraint"},
		{name: "line directive in a body", old: "n := 0", new: "n := 0\n//line other.go:1\n\t_ = n", want: "//line directive"},
		{name: "line directive elsewhere at base", base: strings.Replace(cartGo, "func Empty() {}", "//line shop.rl:10\nfunc Empty() {}", 1),
			old: "n += x", new: "n += x * 1", want: "//line directive"},
		{name: "generated", base: "// Code generated by x. DO NOT EDIT.\n\n" + cartGo, old: "n += x", new: "n += x * 1", want: "generated"},
		{name: "cgo", base: strings.Replace(cartGo, `import "strings"`, "// #include <stdio.h>\nimport \"C\"\nimport \"strings\"", 1),
			old: "n += x", new: "n += x * 1", want: "cgo"},
		{name: "unparsable head", old: "n += x", new: "n += ", want: "head does not parse"},
	}
	for _, c := range cases {
		base := cartGo
		if c.base != "" {
			base = c.base
		}
		head := strings.Replace(base, c.old, c.new, 1)
		if head == base {
			t.Fatalf("%s: no change", c.name)
		}
		_, _, _, why := BodyGuard("shop.go", []byte(base), []byte(head))
		if !strings.Contains(why, c.want) {
			t.Errorf("%s: why %q, want %q", c.name, why, c.want)
		}
	}
	if _, _, _, why := BodyGuard("shop.go", []byte("package"), []byte(cartGo)); !strings.Contains(why, "base does not parse") {
		t.Errorf("unparsable base: %q", why)
	}
}
