func TestSemverSatisfies(t *testing.T) {
	for _, tc := range []struct {
		v, r string
		want bool
	}{
		{"1.2.3", "^1.0.0", true}, {"2.0.0", "^1.0.0", false}, {"0.2.5", "^0.2.3", true}, {"0.3.0", "^0.2.3", false},
		{"1.2.3", "~1.2.0", true}, {"1.3.0", "~1.2.0", false}, {"1.2.3", "1.x", true}, {"1.2.3", "*", true},
		{"1.2.3", "", true}, {"1.2.3", ">=1.0.0 <1.2.3", false}, {"1.2.3", "1.0.0 - 1.2", true}, {"1.3.0", "1.0.0 - 1.2", false},
		{"1.2.3", "^2 || ^1.2", true}, {"1.0.0-beta.2", "^1.0.0-beta.1", true}, {"1.0.1-beta.2", "^1.0.0-beta.1", false},
		{"1.0.0-beta.1", "*", false}, {"1.2.3", "latest", false}, {"1.2.3", ">= 1.2.3", true}, {"1.2.3", "=1.2.3", true},
		{"1.2.3", "<=1.2", true}, {"1.3.0", "<=1.2", false}, {"2.0.0", ">1", true}, {"1.9.0", ">1", false},
	} {
		got, err := semverSatisfies(tc.v, tc.r)
		if err != nil || got != tc.want {
			t.Errorf("satisfies(%s, %q) = %v, %v; want %v", tc.v, tc.r, got, err, tc.want)
		}
	}
	if _, err := semverSatisfies("1.0.0", "^1.0.0 garbage!"); err == nil {
		t.Errorf("unreadable range: no error")
	}
}

