// mapFiles is an in-memory Files.
type mapFiles map[string]string

func (m mapFiles) Read(p string) ([]byte, error) {
	if s, ok := m[p]; ok {
		return []byte(s), nil
	}
	return nil, fs.ErrNotExist
}

func (m mapFiles) Files() []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func with(m mapFiles, k, v string) mapFiles {
	out := mapFiles{}
	for a, b := range m {
		out[a] = b
	}
	out[k] = v
	return out
}

func mustParseFiles(t *testing.T, name, dir, data string, files Files) *Graph {
	t.Helper()
	g, err := ParseFiles(name, dir, []byte(data), files)
	if err != nil {
		t.Fatal(err)
	}
	return g
}

func closureVersions(g *Graph, project string) []string {
	var out []string
	for _, id := range g.Packages(g.Projects[project]) {
		if n := g.Nodes[id]; n != nil && n.Project == "" {
			out = append(out, n.Package+"@"+n.Version)
		}
	}
	sort.Strings(out)
	return out
}

func changed(t *testing.T, base, head *Graph) []string {
	t.Helper()
	d, err := Compare(base, head)
	if err != nil {
		t.Fatal(err)
	}
	return d.ChangedProjects()
}

