func TestBerryClosures(t *testing.T) {
	g := mustParseFiles(t, "yarn.lock", ".", berryLock, berryFiles)
	if g.Format != FormatBerry || g.Version != "8" {
		t.Fatalf("format %s %s", g.Format, g.Version)
	}
	// b: ms through the root resolution (the entry keeps the original ^2.1.0), terser with acorn added by yarn's
	// built-in package extension.
	if got, want := closureVersions(g, "packages/b"), []string{"acorn@8.16.0", "ms@2.1.3", "terser@4.8.1"}; !slices.Equal(got, want) {
		t.Errorf("b: %v, want %v", got, want)
	}
	// a: b through the workspace, the bound link, typescript from the catalog with its built-in patch.
	want := []string{"acorn@8.16.0", "lodash@4.17.21", "ms@2.1.3", "terser@4.8.1", "tool@0.0.0-use.local", "typescript@5.4.5"}
	if got := closureVersions(g, "packages/a"); !slices.Equal(slices.Compact(got), want) {
		t.Errorf("a: %v, want %v", got, want)
	}
	// The built-in compat patch changes with the yarn release: a change of the patch entry changes a.
	head := mustParseFiles(t, "yarn.lock", ".", strings.Replace(berryLock, "hash=5adc0c", "hash=ffffff", 1), berryFiles)
	if got := changed(t, g, head); !slices.Equal(got, []string{"packages/a"}) {
		t.Errorf("patch change: changed %v", got)
	}
	// The package extension's target changes: b, and a through b.
	head = mustParseFiles(t, "yarn.lock", ".", strings.Replace(berryLock, "10/acorn", "10/acorn2", 1), berryFiles)
	if got := changed(t, g, head); !slices.Equal(got, []string{"packages/a", "packages/b"}) {
		t.Errorf("extension target change: changed %v", got)
	}
	// A workspace: range that is not a key yet still resolves to the workspace, as yarn does.
	head = mustParseFiles(t, "yarn.lock", ".", strings.Replace(berryLock, `b: "workspace:^"`, `b: "workspace:^1.0.0"`, 1), berryFiles)
	if got := head.Nodes[head.Nodes[head.Projects["packages/a"]].Deps["b"]]; got == nil || got.Project != "packages/b" {
		t.Errorf("workspace range: a's b is %v", got)
	}
	// cacheKey is outside the graph.
	head = mustParseFiles(t, "yarn.lock", ".", strings.Replace(berryLock, "cacheKey: 10", "cacheKey: 11", 1), berryFiles)
	if _, err := Compare(g, head); err == nil {
		t.Errorf("cacheKey change compared")
	}
}

