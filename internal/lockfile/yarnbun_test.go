func TestYarnV1Workspaces(t *testing.T) {
	g := mustParseFiles(t, "yarn.lock", ".", yarnV1, yarnV1Files)
	if g.Format != FormatYarn {
		t.Fatalf("format %s", g.Format)
	}
	var projects []string
	for p := range g.Projects {
		projects = append(projects, p)
	}
	sort.Strings(projects)
	if want := []string{".", "packages/a", "packages/b", "packages/c"}; !slices.Equal(projects, want) {
		t.Fatalf("projects %v, want %v", projects, want)
	}
	// a: b@^1.0.0 is the workspace (1.2.0 satisfies it); lodash, the alias and @scope/util through both.
	if got, want := closureVersions(g, "packages/a"), []string{"@scope/util@1.0.0", "lodash@4.17.21", "ms@2.1.3"}; !slices.Equal(got, want) {
		t.Errorf("a: %v, want %v", got, want)
	}
	if g.Nodes[g.Nodes[g.Projects["packages/a"]].Deps["b"]].Project != "packages/b" {
		t.Errorf("a's b is not the workspace")
	}
	// c: b@^2.0.0 is not satisfied by the workspace: the registry package.
	if got, want := closureVersions(g, "packages/c"), []string{"b@2.0.0"}; !slices.Equal(got, want) {
		t.Errorf("c: %v, want %v", got, want)
	}
	if got, want := closureVersions(g, "."), []string{"@scope/util@1.0.0", "lodash@4.17.21", "vitest@1.0.0"}; !slices.Equal(got, want) {
		t.Errorf("root: %v, want %v", got, want)
	}
}

func TestYarnV1Changes(t *testing.T) {
	base := mustParseFiles(t, "yarn.lock", ".", yarnV1, yarnV1Files)
	// @scope/util changes: everything that reaches it (a and the root through lodash, b directly).
	head := mustParseFiles(t, "yarn.lock", ".", strings.Replace(yarnV1, "sha512-util", "sha512-util2", 1), yarnV1Files)
	if got, want := changed(t, base, head), []string{".", "packages/a", "packages/b"}; !slices.Equal(got, want) {
		t.Errorf("changed %v, want %v", got, want)
	}
	// The registry b only reaches c.
	head = mustParseFiles(t, "yarn.lock", ".", strings.Replace(yarnV1, `version "2.0.0"`, `version "2.0.1"`, 1), yarnV1Files)
	if got, want := changed(t, base, head), []string{"packages/c"}; !slices.Equal(got, want) {
		t.Errorf("changed %v, want %v", got, want)
	}
	// The workspace b's version no longer satisfies a's range: a now resolves to the registry entry... which the
	// lockfile lacks: an error (level L0).
	files := with(yarnV1Files, "packages/b/package.json", `{"name":"b","version":"3.0.0"}`)
	if _, err := ParseFiles("yarn.lock", ".", []byte(yarnV1), files); err == nil || !strings.Contains(err.Error(), "b@^1.0.0") {
		t.Errorf("unresolvable dependency: err %v", err)
	}
}

