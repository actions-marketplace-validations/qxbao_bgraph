func TestBunManifestDeclarations(t *testing.T) {
	// The lockfile dropped a's devDependency on debug (also a peer); bun installs it, the closure has it.
	files := with(bunFiles, "packages/a/package.json", `{"name":"@x/a","dependencies":{"@x/b":"workspace:*","debug":"^4"},"devDependencies":{"vitest":"^1.0.0"}}`)
	g := mustParseFiles(t, "bun.lock", ".", bunLock, files)
	if got, want := closureVersions(g, "packages/a"), []string{"debug@4.3.4", "ms@2.0.0", "ms@2.1.2", "ms@2.1.3", "vitest@1.0.0"}; !slices.Equal(got, want) {
		t.Errorf("a: %v, want %v", got, want)
	}
	// A declared dependency the lockfile cannot resolve: the lockfile is stale.
	files = with(bunFiles, "packages/a/package.json", `{"name":"@x/a","devDependencies":{"left-pad":"^1"}}`)
	if _, err := ParseFiles("bun.lock", ".", []byte(bunLock), files); err == nil || !strings.Contains(err.Error(), "left-pad") {
		t.Errorf("stale lockfile: err %v", err)
	}
	if _, err := ParseFiles("bun.lock", ".", []byte(bunLock), nil); err == nil {
		t.Errorf("no manifests: parsed")
	}
}

func TestBunNestedResolution(t *testing.T) {
	g := mustParseFiles(t, "bun.lock", ".", bunLock, bunFiles)
	if g.Format != FormatBun {
		t.Fatalf("format %s", g.Format)
	}
	// b's ms is the copy nested under the workspace; debug's ms the one nested under debug; the root's the hoisted one.
	if got, want := closureVersions(g, "packages/b"), []string{"ms@2.0.0"}; !slices.Equal(got, want) {
		t.Errorf("b: %v, want %v", got, want)
	}
	if got, want := closureVersions(g, "packages/a"), []string{"debug@4.3.4", "ms@2.0.0", "ms@2.1.2"}; !slices.Equal(got, want) {
		t.Errorf("a: %v, want %v", got, want)
	}
	if got, want := closureVersions(g, "."), []string{"ms@2.1.3", "vitest@1.0.0"}; !slices.Equal(got, want) {
		t.Errorf("root: %v, want %v", got, want)
	}
	head := mustParseFiles(t, "bun.lock", ".", strings.Replace(bunLock, "sha512-ms212", "sha512-ms212b", 1), bunFiles)
	if got := changed(t, g, head); !slices.Equal(got, []string{"packages/a"}) {
		t.Errorf("changed %v", got)
	}
	// overrides steer resolution only: compared through the closures.
	head = mustParseFiles(t, "bun.lock", ".", strings.Replace(bunLock, `"packages": {`, `"overrides": {"ms": "2.1.3"}, "packages": {`, 1), bunFiles)
	if got := changed(t, g, head); len(got) != 0 {
		t.Errorf("override only: changed %v", got)
	}
	// trustedDependencies is outside the graph.
	head = mustParseFiles(t, "bun.lock", ".", strings.Replace(bunLock, `"packages": {`, `"trustedDependencies": ["esbuild"], "packages": {`, 1), bunFiles)
	if _, err := Compare(g, head); err == nil {
		t.Errorf("trustedDependencies change compared")
	}
}

