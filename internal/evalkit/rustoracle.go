package evalkit

import (
	"path"
	"regexp"
	"sort"
	"strings"

	"github.com/qxbao/bgraph/internal/tree"
)

// RustTestLoc is where one Rust FAIL_TO_PASS test name is defined, as far as a source scan can tell.
//
// Phase 1 (this file) only locates .rs files. TODO(rust-phase-2): once internal/eco/rust lands, map Files / DocFile to Cargo target
// units (lib, bin, integration test, doc-test of a package) and run T1 against them; ambiguous names should then require the union of the
// units of all candidate files, and NotFound names should be reported as unmapped (never silently dropped).
type RustTestLoc struct {
	Name      string
	Files     []string // candidate .rs files (sorted) defining the test; for doc-tests, tree files matching DocFile
	Doc       bool     // doc-test ("src/lib.rs - item (line N)")
	DocFile   string   // doc-test: the file path as written in the name (may be relative to the crate root, not the repo root)
	Ambiguous bool     // more than one candidate file
	NotFound  bool     // no candidate file with a literal `fn <name>` (e.g. test generated by a macro, or not a .rs-defined test)
	// MacroFiles are files that invoke a test-like macro with the name as first argument (rgtest!(r1319, ...), test!(name, ...));
	// a heuristic for NotFound names, never mixed into Files.
	MacroFiles []string
}

var (
	rustDocName = regexp.MustCompile(`^\s*(\S+\.rs)\s+-\s+.*\(line\s+\d+\)\s*$`)
	rustFnDef   = regexp.MustCompile(`\bfn\s+(?:r#)?([A-Za-z_][A-Za-z0-9_]*)`)
	rustModDef  = regexp.MustCompile(`\bmod\s+([A-Za-z_][A-Za-z0-9_]*)\s*[{;]`)
	// Head of an attribute whose path mentions "test": #[test], #[tokio::test(..)], #[rstest], #[test_case(..)], #[async_std::test].
	rustTestAttr = regexp.MustCompile(`#\s*!?\[\s*([A-Za-z0-9_:]*[Tt][Ee][Ss][Tt][A-Za-z0-9_:]*)`)
	rustCaseName = regexp.MustCompile(`^case_\d+$`)
	rustMacroUse = regexp.MustCompile(`([A-Za-z_][A-Za-z0-9_]*)!\s*[({\[]\s*([A-Za-z_][A-Za-z0-9_]*)\s*[,)]`)
)

// rustFileInfo is what the scan learned about one file that defines tests.
type rustFileInfo struct {
	mods  map[string]bool // inline `mod x` names
	stems []string        // path components (dirs and file stem) usable as module names
}

// LocateRustTests locates the defining files of each FAIL_TO_PASS name in tree t (the P tree: base + test patch).
// Precision matters less than recall: attributes are matched loosely and the module path only narrows candidates when that leaves some.
func LocateRustTests(t tree.Tree, names []string) []RustTestLoc {
	out := make([]RustTestLoc, len(names))
	fns := map[string]map[string]bool{}    // fn name -> files defining a test fn of that name
	macros := map[string]map[string]bool{} // test-like macro first argument -> files
	infos := map[string]*rustFileInfo{}
	need := false
	for _, n := range names {
		if !rustDocName.MatchString(n) {
			need = true
			break
		}
	}
	if need {
		for _, p := range t.Files() {
			if !strings.HasSuffix(p, ".rs") {
				continue
			}
			b, err := t.Read(p)
			if err != nil {
				continue
			}
			scanRustFile(p, string(b), fns, macros, infos)
		}
	}
	for i, n := range names {
		out[i] = locateOne(t, n, fns, infos)
		if out[i].NotFound && !out[i].Doc {
			out[i].MacroFiles = sortedKeys(macros[lastSegmentOf(n)])
		}
	}
	return out
}

func locateOne(t tree.Tree, name string, fns map[string]map[string]bool, infos map[string]*rustFileInfo) RustTestLoc {
	loc := RustTestLoc{Name: name}
	if m := rustDocName.FindStringSubmatch(name); m != nil {
		loc.Doc, loc.DocFile = true, m[1]
		for _, p := range t.Files() {
			if p == m[1] || strings.HasSuffix(p, "/"+m[1]) {
				loc.Files = append(loc.Files, p)
			}
		}
		finish(&loc)
		return loc
	}
	if n := strings.TrimSpace(name); strings.HasSuffix(n, ".rs") && !strings.ContainsAny(n, " :") {
		// trybuild-style UI test ("tests/ui/foo.rs"): the name is the file itself.
		for _, p := range t.Files() {
			if p == n || strings.HasSuffix(p, "/"+n) {
				loc.Files = append(loc.Files, p)
			}
		}
		finish(&loc)
		return loc
	}
	segs := strings.Split(strings.TrimSpace(name), "::")
	last := segs[len(segs)-1]
	mods := segs[:len(segs)-1]
	cands := fns[last]
	if len(cands) == 0 && len(segs) > 1 && rustCaseName.MatchString(last) {
		// rstest/test_case generate `<fn>::case_N`: the defining fn is the previous segment.
		last = segs[len(segs)-2]
		mods = segs[:len(segs)-2]
		cands = fns[last]
	}
	var files []string
	for f := range cands {
		files = append(files, f)
	}
	sort.Strings(files)
	if len(mods) > 0 && len(files) > 1 {
		var keep []string
		for _, f := range files {
			if moduleConsistent(infos[f], mods) {
				keep = append(keep, f)
			}
		}
		if len(keep) > 0 {
			files = keep
		}
	}
	loc.Files = files
	finish(&loc)
	return loc
}

func finish(l *RustTestLoc) {
	sort.Strings(l.Files)
	l.Ambiguous = len(l.Files) > 1
	l.NotFound = len(l.Files) == 0
}

// moduleConsistent: every module segment is a path component / file stem or an inline `mod` of the file.
func moduleConsistent(fi *rustFileInfo, mods []string) bool {
	if fi == nil {
		return false
	}
	for _, m := range mods {
		ok := fi.mods[m]
		for _, s := range fi.stems {
			if s == m {
				ok = true
				break
			}
		}
		if !ok {
			return false
		}
	}
	return true
}

func scanRustFile(p, src string, fns, macros map[string]map[string]bool, infos map[string]*rustFileInfo) {
	if !strings.Contains(src, "fn ") && !strings.Contains(src, "!") {
		return
	}
	m := maskRust(src)
	for _, mm := range rustMacroUse.FindAllStringSubmatch(m, -1) {
		if strings.Contains(strings.ToLower(mm[1]), "test") {
			if macros[mm[2]] == nil {
				macros[mm[2]] = map[string]bool{}
			}
			macros[mm[2]][p] = true
		}
	}
	var info *rustFileInfo
	for _, l := range rustFnDef.FindAllStringSubmatchIndex(m, -1) {
		if !hasTestAttr(m, l[0]) {
			continue
		}
		name := m[l[2]:l[3]]
		if fns[name] == nil {
			fns[name] = map[string]bool{}
		}
		fns[name][p] = true
		if info != nil {
			continue
		}
		info = &rustFileInfo{mods: map[string]bool{}}
		for _, mm := range rustModDef.FindAllStringSubmatch(m, -1) {
			info.mods[mm[1]] = true
		}
		for _, c := range strings.Split(strings.TrimSuffix(p, ".rs"), "/") {
			if c != "" {
				info.stems = append(info.stems, c)
			}
		}
		// foo/mod.rs, lib.rs and main.rs do not name a module.
		if b := path.Base(p); b == "mod.rs" || b == "lib.rs" || b == "main.rs" {
			info.stems = info.stems[:len(info.stems)-1]
		}
		infos[p] = info
	}
}

// hasTestAttr looks back from the `fn` keyword at the attribute block that precedes it: up to 12 lines, stopping at the end of the
// previous item (a line ending in `}` or `;`) or at another fn.
func hasTestAttr(m string, fnPos int) bool {
	start := strings.LastIndexByte(m[:fnPos], '\n') + 1
	lines := []string{m[start:fnPos]}
	for n := 0; n < 12 && start > 0; n++ {
		s := strings.LastIndexByte(m[:start-1], '\n') + 1
		ln := strings.TrimSpace(m[s : start-1])
		if strings.HasSuffix(ln, "}") || strings.HasSuffix(ln, ";") || rustFnDef.MatchString(ln) {
			break
		}
		lines = append(lines, ln)
		start = s
	}
	return rustTestAttr.MatchString(strings.Join(lines, "\n"))
}

// maskRust blanks comments and string/char literals (keeping length and newlines) so that textual searches do not hit them.
func maskRust(s string) string {
	b := []byte(s)
	blank := func(from, to int) {
		for i := from; i < to && i < len(b); i++ {
			if b[i] != '\n' {
				b[i] = ' '
			}
		}
	}
	n := len(b)
	for i := 0; i < n; {
		c := b[i]
		switch {
		case c == '/' && i+1 < n && b[i+1] == '/':
			j := i
			for j < n && b[j] != '\n' {
				j++
			}
			blank(i, j)
			i = j
		case c == '/' && i+1 < n && b[i+1] == '*':
			depth, j := 1, i+2
			for j < n && depth > 0 {
				switch {
				case b[j] == '/' && j+1 < n && b[j+1] == '*':
					depth++
					j += 2
				case b[j] == '*' && j+1 < n && b[j+1] == '/':
					depth--
					j += 2
				default:
					j++
				}
			}
			blank(i, j)
			i = j
		case c == '"':
			j := i + 1
			for j < n && b[j] != '"' {
				if b[j] == '\\' {
					j++
				}
				j++
			}
			j++
			blank(i+1, j-1)
			i = j
		case c == 'r' && (i == 0 || !isIdentByte(b[i-1])) && rawStringStart(b, i) >= 0:
			hashes := rawStringStart(b, i)
			j := i + 1 + hashes + 1
			closer := "\"" + strings.Repeat("#", hashes)
			k := strings.Index(string(b[j:]), closer)
			if k < 0 {
				k = n - j
			}
			blank(j, j+k)
			i = j + k + len(closer)
		case c == '\'':
			// char literal 'x' / '\n' / '\u{..}' versus lifetime 'a.
			if i+2 < n && b[i+1] == '\\' {
				j := i + 2
				for j < n && b[j] != '\'' && j < i+12 {
					j++
				}
				blank(i+1, j)
				i = j + 1
			} else if i+2 < n && b[i+2] == '\'' {
				blank(i+1, i+2)
				i += 3
			} else {
				i++
			}
		default:
			i++
		}
	}
	return string(b)
}

func isIdentByte(c byte) bool {
	return c == '_' || c >= '0' && c <= '9' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z'
}

// rawStringStart returns the number of '#' of a raw string opener r#"..."# at b[i] (0 for r"..."), or -1 if b[i:] is not one.
func rawStringStart(b []byte, i int) int {
	j := i + 1
	h := 0
	for j < len(b) && b[j] == '#' {
		h++
		j++
	}
	if j < len(b) && b[j] == '"' {
		return h
	}
	return -1
}

func lastSegmentOf(name string) string {
	segs := strings.Split(strings.TrimSpace(name), "::")
	return segs[len(segs)-1]
}

func sortedKeys(m map[string]bool) []string {
	var out []string
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
