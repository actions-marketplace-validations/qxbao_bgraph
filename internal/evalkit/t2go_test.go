func TestGoScan(t *testing.T) {
	src := []byte("package p\n\n// a == b in a comment\nfunc f(a, b int, s string) bool {\n\tx := \"a\" + s\n\t_ = x\n\treturn a+1 < b && true\n}\n")
	cands, ok := goScan(src)
	if !ok {
		t.Fatal("not parsed")
	}
	var got []string
	for _, c := range cands {
		got = append(got, c.Op+":"+string(src[c.Start:c.End])+">"+c.Repl)
	}
	sort.Strings(got)
	want := []string{"add-sub:+>-", "and-or:&&>||", "lt-ge:<>>=", "true-false:true>false"}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("got %v want %v", got, want)
	}
	if _, ok := goScan([]byte("// Code generated by x. DO NOT EDIT.\n\npackage p\nvar a = 1 == 2\n")); ok {
		t.Fatal("generated file scanned")
	}
}

func TestGoMutableFile(t *testing.T) {
	bctx := build.Default
	bctx.GOOS = "windows"
	cases := map[string]bool{
		"a.go": true, "x/a_test.go": false, "testdata/a.go": false, "_x/a.go": false, "vendor/x/a.go": false, "x/a_linux.go": false,
	}
	for f, want := range cases {
		if got := goMutableFile(f, []byte("package p\n"), &bctx); got != want {
			t.Errorf("%s: got %v", f, got)
		}
	}
	if goMutableFile("x/b.go", []byte("//go:build linux\n\npackage p\n"), &bctx) {
		t.Error("build constraint ignored")
	}
}

func TestParseGoTestJSON(t *testing.T) {
	gl := &goLayout{modules: []goModule{{Dir: "sub", Path: "example.com/m/sub"}, {Dir: ".", Path: "example.com/m"}}, units: map[string]bool{}}
	out := `{"Action":"start","Package":"example.com/m"}
{"Action":"run","Package":"example.com/m","Test":"TestA"}
{"Action":"fail","Package":"example.com/m","Test":"TestA"}
{"Action":"fail","Package":"example.com/m","Test":"TestA/sub"}
{"Action":"fail","Package":"example.com/m"}
{"Action":"pass","Package":"example.com/m/x"}
{"ImportPath":"example.com/m/sub/y [example.com/m/sub/y.test]","Action":"build-fail"}
{"Action":"fail","Package":"example.com/m/sub/y","FailedBuild":"example.com/m/sub/y [example.com/m/sub/y.test]"}
go: warning
`
	run := GoRun{Units: map[string]string{}, Names: map[string][]string{}}
	gl.parseGoTestJSON(out, &run)
	want := map[string]string{"go:.": "failed", "go:x": "passed", "go:sub/y": "failed"}
	if !reflect.DeepEqual(run.Units, want) {
		t.Fatalf("units %v", run.Units)
	}
	if !reflect.DeepEqual(run.Names["go:."], []string{"TestA"}) {
		t.Fatalf("names %v", run.Names)
	}
	if m := gl.moduleOfDir("sub/y"); m == nil || m.Dir != "sub" || moduleArg(m, "sub/y") != "./y" || moduleArg(m, "sub") != "." {
		t.Fatalf("module of sub/y: %+v", m)
	}
}
