package agent

import (
	"strings"
)

// Markers delimit the block bgraph owns in an instruction file (CLAUDE.md, AGENTS.md). Everything between them is replaced on
// install and removed on uninstall; everything outside them is left as it is.
const (
	BlockStart = "<!-- bgraph:start -->"
	BlockEnd   = "<!-- bgraph:end -->"
)

// SkillName is the name of the skill Install writes (`/bgraph-test`).
const SkillName = "bgraph-test"

// skillMarker identifies a SKILL.md written by bgraph, so Uninstall never removes a skill the user wrote under the same name.
const skillMarker = "<!-- generated by `bgraph agent install`; `bgraph agent uninstall` removes it -->"

// Block is the instruction-file text, without the markers: short, factual, and readable by subagents, which do not see the
// MCP server instructions. It points at the CLI, so it works with or without the MCP server.
func Block() string {
	return `## Running tests: bgraph

This repository uses bgraph to select the tests a change can affect.

- After changing code, run ` + "`bgraph command`" + ` and run the command lines it prints, from the repository root, instead of the whole test suite. It compares the working tree (uncommitted changes included) with the merge-base of the default branch; ` + "`--base REF`" + ` picks another base.
- ` + "`# scope: full`" + ` with no command line means the selection could not be narrowed: run the whole suite. ` + "`# scope: none`" + ` means no test is affected.
- ` + "`bgraph explain <test-or-file>`" + ` says why a test was or was not selected. The bgraph MCP server, when connected, offers the same through ` + "`test_commands`" + ` and ` + "`dependents_of`" + `.
- The selection shortens the edit-and-test loop; the project's CI remains the final check before merge.
`
}

// Skill is the SKILL.md of the `bgraph-test` skill: running the affected tests on request or before reporting a change as done.
func Skill() string {
	return `---
name: ` + SkillName + `
description: Run only the tests affected by the current change, as selected by bgraph. Use after editing code, before reporting a change as done, or when asked to run the affected or relevant tests.
---
` + skillMarker + `

# Run the affected tests

1. From the repository root, run ` + "`bgraph command`" + `. It compares the working tree with the merge-base of the default branch; add ` + "`--base REF`" + ` to compare with another base (for example the commit the task started from).
2. Read the ` + "`# scope:`" + ` line:
   - ` + "`none`" + `: no test is affected. Say so; there is nothing to run.
   - ` + "`full`" + `: bgraph could not narrow the selection (the ` + "`#`" + ` lines say why). Run the project's whole test suite.
   - ` + "`graph`" + `, ` + "`package`" + ` or ` + "`module`" + `: run every printed command, in order, from the repository root.
3. If a test fails, fix the cause and repeat from step 1.
4. Report the scope and the commands that ran. Do not describe a narrowed run as the full suite.

To see why a test was or was not selected: ` + "`bgraph explain <test-or-file>`" + `. To see what depends on a file before changing it, use the ` + "`dependents_of`" + ` tool of the bgraph MCP server when it is connected.
`
}

// UpsertBlock returns content with block between BlockStart and BlockEnd: the existing marked block is replaced, or the block
// is appended after a blank line. The file's line endings (CRLF or LF) are kept. A start marker without an end marker is left
// alone and the block is appended, so a damaged file never loses text.
func UpsertBlock(content, block string) string {
	nl := "\n"
	if strings.Contains(content, "\r\n") {
		nl = "\r\n"
	}
	marked := BlockStart + "\n" + strings.TrimRight(block, "\n") + "\n" + BlockEnd
	marked = strings.ReplaceAll(marked, "\n", nl)
	if i, j, ok := blockSpan(content); ok {
		return content[:i] + marked + content[j:]
	}
	if strings.TrimSpace(content) == "" {
		return marked + nl
	}
	trimmed := strings.TrimRight(content, "\r\n")
	return trimmed + nl + nl + marked + nl
}

// RemoveBlock returns content without the marked block and the blank lines that separated it, and whether a block was found.
func RemoveBlock(content string) (string, bool) {
	i, j, ok := blockSpan(content)
	if !ok {
		return content, false
	}
	before, after := strings.TrimRight(content[:i], "\r\n"), strings.TrimLeft(content[j:], "\r\n")
	nl := "\n"
	if strings.Contains(content, "\r\n") {
		nl = "\r\n"
	}
	switch {
	case before == "":
		return after, true
	case after == "":
		return before + nl, true
	}
	return before + nl + nl + after, true
}

// blockSpan finds the marked block: [i, j) covers BlockStart through BlockEnd.
func blockSpan(content string) (i, j int, ok bool) {
	i = strings.Index(content, BlockStart)
	if i < 0 {
		return 0, 0, false
	}
	k := strings.Index(content[i:], BlockEnd)
	if k < 0 {
		return 0, 0, false
	}
	return i, i + k + len(BlockEnd), true
}
